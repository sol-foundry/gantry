import type { DdlRequest, SqlService } from "@/types";

export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  const units = ["KB", "MB", "GB", "TB"];
  let value = bytes / 1024;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit++;
  }
  return `${value.toFixed(value < 10 ? 1 : 0)} ${units[unit]}`;
}

/** Postgres reports "PostgreSQL 16.4 on aarch64-unknown-linux-musl, compiled by ..."; the build details are noise. */
export function shortVersion(version: string): string {
  return version.split(" on ")[0];
}

export function qualifiedName(hasSchemas: boolean, schema: string, table: string): string {
  return hasSchemas ? `${schema}.${table}` : table;
}

export function plural(count: number, noun: string): string {
  return `${count} ${noun}${count === 1 ? "" : "s"}`;
}

